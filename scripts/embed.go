func Manifest() (map[string]string, error) {
	out := map[string]string{}
	for _, name := range sources.names() {
		data, err := Source(name)
		if err != nil {
			return nil, err
		}
		hash := sha256.Sum256(data)
		out[name] = hex.EncodeToString(hash[:])
	}
	return out, nil
}
