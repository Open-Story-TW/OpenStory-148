CREATE TABLE asset_storages (
 account_id bigint NOT NULL REFERENCES auth_accounts(id),
 world_id integer NOT NULL CHECK(world_id BETWEEN 0 AND 127),
 capacity integer NOT NULL DEFAULT 48 CHECK(capacity BETWEEN 1 AND 128),
 mesos bigint NOT NULL DEFAULT 0 CHECK(mesos BETWEEN 0 AND 2147483647),
 revision bigint NOT NULL DEFAULT 1,
 PRIMARY KEY(account_id,world_id)
);
CREATE TABLE asset_storage_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id bigint NOT NULL,
 world_id integer NOT NULL,
 position integer NOT NULL CHECK(position BETWEEN 1 AND 128),
 inv_type smallint NOT NULL CHECK(inv_type BETWEEN 1 AND 4),
 template_id integer NOT NULL CHECK(template_id>0),
 quantity integer NOT NULL CHECK(quantity BETWEEN 1 AND 30000),
 equipment jsonb,
 FOREIGN KEY(account_id,world_id) REFERENCES asset_storages(account_id,world_id) ON DELETE CASCADE,
 UNIQUE(account_id,world_id,position) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE asset_storage_operations (
 operation_id text PRIMARY KEY,
 account_id bigint NOT NULL REFERENCES auth_accounts(id),
 world_id integer NOT NULL,
 character_id bigint NOT NULL REFERENCES game_characters(id),
 request_hash text NOT NULL,
 result jsonb NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
