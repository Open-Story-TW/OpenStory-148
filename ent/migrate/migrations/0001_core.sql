CREATE TABLE auth_accounts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id > 0 AND id <= 2147483647),
 name text NOT NULL, name_key text NOT NULL UNIQUE, password_hash text NOT NULL,
 pin_hash text NOT NULL DEFAULT '', gender integer NOT NULL DEFAULT 255 CHECK(gender IN(0,1,255)),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE game_characters (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id > 0 AND id <= 2147483647),
 account_id bigint NOT NULL REFERENCES auth_accounts(id), world_id integer NOT NULL CHECK(world_id BETWEEN 0 AND 127),
 name text NOT NULL, name_key text NOT NULL UNIQUE, operation_id text NOT NULL UNIQUE,
 gender integer NOT NULL CHECK(gender IN(0,1)), skin integer NOT NULL, face integer NOT NULL, hair integer NOT NULL,
 level integer NOT NULL DEFAULT 1 CHECK(level BETWEEN 1 AND 2147483647), job integer NOT NULL DEFAULT 0,
 str integer NOT NULL DEFAULT 12, dex integer NOT NULL DEFAULT 5, int_stat integer NOT NULL DEFAULT 4, luk integer NOT NULL DEFAULT 4,
 hp integer NOT NULL DEFAULT 50,mp integer NOT NULL DEFAULT 5,max_hp integer NOT NULL DEFAULT 50,max_mp integer NOT NULL DEFAULT 5,
 ap integer NOT NULL DEFAULT 0,sp integer NOT NULL DEFAULT 0,exp bigint NOT NULL DEFAULT 0 CHECK(exp BETWEEN 0 AND 2147483647),
 fame integer NOT NULL DEFAULT 0,mesos bigint NOT NULL DEFAULT 0 CHECK(mesos BETWEEN 0 AND 2147483647),
 map_id integer NOT NULL DEFAULT 10000,spawn_point integer NOT NULL DEFAULT 0,x integer NOT NULL DEFAULT -192,y integer NOT NULL DEFAULT 210,
 gm integer NOT NULL DEFAULT 0 CHECK(gm=0),revision bigint NOT NULL DEFAULT 1 CHECK(revision>0)
);
CREATE INDEX game_characters_account_world ON game_characters(account_id,world_id);
CREATE TABLE asset_equipment (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 character_id bigint NOT NULL REFERENCES game_characters(id) ON DELETE CASCADE,
 item_id integer NOT NULL,slot integer NOT NULL,
 str integer NOT NULL DEFAULT 0,dex integer NOT NULL DEFAULT 0,int_stat integer NOT NULL DEFAULT 0,luk integer NOT NULL DEFAULT 0,
 hp integer NOT NULL DEFAULT 0,mp integer NOT NULL DEFAULT 0,watk integer NOT NULL DEFAULT 0,matk integer NOT NULL DEFAULT 0,
 wdef integer NOT NULL DEFAULT 0,mdef integer NOT NULL DEFAULT 0,acc integer NOT NULL DEFAULT 0,avoid integer NOT NULL DEFAULT 0,
 speed integer NOT NULL DEFAULT 0,jump integer NOT NULL DEFAULT 0,upgrade_slots integer NOT NULL DEFAULT 7,
 UNIQUE(character_id,slot)
);
CREATE TABLE game_character_roster (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id bigint NOT NULL REFERENCES auth_accounts(id),world_id integer NOT NULL,
 character_id bigint NOT NULL UNIQUE REFERENCES game_characters(id) ON DELETE CASCADE,
 snapshot jsonb NOT NULL,revision bigint NOT NULL DEFAULT 1
);
CREATE INDEX game_character_roster_account_world ON game_character_roster(account_id,world_id);
CREATE TABLE ops_runtime_leases (
 world_id integer PRIMARY KEY,instance_id text NOT NULL,epoch bigint NOT NULL CHECK(epoch>0),expires_at timestamptz NOT NULL
);
CREATE TABLE ops_account_sessions (
 account_id bigint PRIMARY KEY REFERENCES auth_accounts(id),session_id text NOT NULL,generation bigint NOT NULL DEFAULT 1,
 state text NOT NULL CHECK(state IN('offline','login','transfer','world')),
 world_id integer NOT NULL DEFAULT -1,character_id bigint NOT NULL DEFAULT 0,
 owner_instance text NOT NULL DEFAULT '',world_epoch bigint NOT NULL DEFAULT 0,
 expires_at timestamptz NOT NULL DEFAULT now()+interval '120 seconds'
);
CREATE TABLE ops_transfers (
 id text PRIMARY KEY,token_hash text NOT NULL UNIQUE,client_handle integer NOT NULL UNIQUE CHECK(client_handle>0),
 account_id bigint NOT NULL REFERENCES auth_accounts(id),character_id bigint NOT NULL REFERENCES game_characters(id),
 world_id integer NOT NULL,channel_id integer NOT NULL CHECK(channel_id>0),session_id text NOT NULL,client_ip text NOT NULL,
 target_instance text NOT NULL,target_epoch bigint NOT NULL,
 expires_at timestamptz NOT NULL,consumed_at timestamptz
);
CREATE INDEX ops_transfers_pending ON ops_transfers(character_id,world_id,channel_id) WHERE consumed_at IS NULL;
CREATE TABLE ops_character_ownership (
 character_id bigint PRIMARY KEY REFERENCES game_characters(id),account_id bigint NOT NULL REFERENCES auth_accounts(id),
 world_id integer NOT NULL,instance_id text NOT NULL,epoch bigint NOT NULL,session_id text NOT NULL,generation bigint NOT NULL,channel_id integer NOT NULL
);
CREATE TABLE ops_outbox (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_type text NOT NULL,account_id bigint NOT NULL,
 world_id integer NOT NULL,created_at timestamptz NOT NULL DEFAULT now(),processed_at timestamptz
);
CREATE INDEX ops_outbox_pending ON ops_outbox(id) WHERE processed_at IS NULL;
