CREATE TABLE asset_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 character_id bigint NOT NULL REFERENCES game_characters(id) ON DELETE CASCADE,
 inv_type smallint NOT NULL CHECK(inv_type BETWEEN 1 AND 5),
 slot smallint NOT NULL CHECK(slot BETWEEN 1 AND 128),
 template_id integer NOT NULL CHECK(template_id > 0),
 quantity integer NOT NULL CHECK(quantity BETWEEN 1 AND 30000),
 revision bigint NOT NULL DEFAULT 1 CHECK(revision > 0),
 UNIQUE(character_id, inv_type, slot)
);
CREATE INDEX asset_items_character ON asset_items(character_id, inv_type, slot);
