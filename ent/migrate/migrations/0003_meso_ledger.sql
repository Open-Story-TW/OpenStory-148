CREATE TABLE asset_meso_ledger (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operation_id text NOT NULL UNIQUE,
 character_id bigint NOT NULL REFERENCES game_characters(id),
 account_id bigint NOT NULL REFERENCES auth_accounts(id),
 world_id integer NOT NULL,
 delta bigint NOT NULL CHECK(delta <> 0),
 balance_after bigint NOT NULL CHECK(balance_after BETWEEN 0 AND 2147483647),
 reason text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX asset_meso_ledger_character ON asset_meso_ledger(character_id, id DESC);
