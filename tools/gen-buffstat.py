"""Generate internal/buffstat/table.go.

Wire layout comes from Open-Maple docs/server/baseline/buffstat-native.json (IDA audit of the
v145 client). Stat names come from Java Legacy src/properties/buffstatus.properties
(the file MapleBuffStatus.reloadValues actually loads); names are semantics
only and still need per-skill MCP proof.

    py -I tools/gen-buffstat.py --java ../MapleStory_Legacy_Server
"""

import argparse
import json
import pathlib
import re

VALUE = {"U8": "ValueU8", "I16": "ValueI16", "I32": "ValueI32", "22xI32": "ValueI32x22"}


def java_names(path):
    names = {}
    for raw in path.read_text(encoding="latin-1").splitlines():
        line = raw.strip()
        m = re.fullmatch(r"([A-Z][A-Z0-9_]*)\s*=\s*(\d+)", line)
        if not m:
            continue
        name, bit = m.group(1), int(m.group(2))
        if re.fullmatch(r"(BUFF|UNKNOWN)_?\d*", name) or name in ("DEFAULTBUFF1", "DEFAULTBUFF2"):
            continue
        names.setdefault(bit, [])
        if name not in names[bit]:
            names[bit].append(name)
    # Two-state stats are enum-only in Java (ENERGY_CHARGE(248) ...).
    for bit, name in enumerate(["ENERGY_CHARGE", "DASH_SPEED", "DASH_JUMP", "MONSTER_RIDING", "SPEED_INFUSION", "HOMING_BEACON"], 248):
        names.setdefault(bit, [name])
    return names


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--java", required=True)
    p.add_argument("--evidence", default="../open-maple/docs/server/baseline/buffstat-native.json")
    p.add_argument("--output", default="internal/buffstat/table.go")
    a = p.parse_args()
    ev = json.loads(pathlib.Path(a.evidence).read_text(encoding="utf-8"))
    names = java_names(pathlib.Path(a.java) / "src/properties/buffstatus.properties")

    rows = {}

    def row(bit):
        return rows.setdefault(bit, {"bit": bit, "order": 0, "tail": [], "tail_order": 0, "remote": [], "remote_order": 0,
                                     "forces_int": False, "move_tail": False, "verified": []})

    for i, bit in enumerate(ev["triplet_order"], 1):
        r = row(bit)
        r["order"] = i
        r["verified"].append("local#%d" % i)
    tail_order = 0
    for step in ev["after_triplets"]:
        if step.get("unconditional") or "if" in step and step["read"].startswith("none"):
            continue
        if "two_state" in step:
            continue
        if "indie" in step:
            continue
        tail_order += 1
        read = step["read"].split(" ")[0]
        for bit in step.get("if_any", [step.get("if")]):
            r = row(bit)
            r["tail"] = [VALUE[read]]
            r["tail_order"] = tail_order
            r["verified"].append("tail#%d" % tail_order)
    order = 0
    for block in ev["remote_blocks"]:
        r = row(block["bit"])
        if r["remote_order"] == 0:
            order += 1
            r["remote_order"] = order
            r["verified"].append("remote#%d" % order)
        r["remote"] += [VALUE[v] for v in block["reads"]]
    two_state_kind = {"base + term U16": "TwoStateTerm", "base": "TwoStateNoExpire",
                      "base + time (sign U8 + delta I32) + term U16": "TwoStateBooster", "base + I32 + I32": "TwoStateGuided"}
    for bit, layout in ev["two_state"]["layouts"].items():
        r = row(int(bit))
        r["two_state_kind"] = two_state_kind[layout["reads"]]
        r["verified"].append("twostate@" + layout["decode"])
    for i, bit in enumerate(ev["indie"]["order"], 1):
        r = row(bit)
        r["indie"] = i
        r["verified"].append("indie#%d" % i)
    for bit in ev["is_encode_int"]["flags"].values():
        row(bit)["forces_int"] = True
    for bit in ev["movement_tail"]["bits"]:
        row(bit)["move_tail"] = True
    for bit in names:
        row(bit)

    out = ["// Code generated by tools/gen-buffstat.py; DO NOT EDIT.", "",
           "package buffstat", "",
           "// Names: Java buffstatus.properties. Layout: Open-Maple docs/server/baseline/buffstat-native.json.",
           "var table = []Spec{"]
    used = set()
    for bit in sorted(rows):
        r = rows[bit]
        alias = [n for n in names.get(bit, []) if n not in used]
        name = alias[0] if alias else "BIT_%d" % bit
        used.update(alias)
        fields = ["Name: %s" % json.dumps(name), "Bit: %d" % bit]
        if alias[1:]:
            fields.append("Aliases: []Stat{%s}" % ", ".join(json.dumps(n) for n in alias[1:]))
        if r["order"]:
            fields.append("Order: %d" % r["order"])
        if r["tail"]:
            fields.append("TailOrder: %d, Tail: []Value{%s}" % (r["tail_order"], ", ".join(r["tail"])))
        if r["remote_order"]:
            fields.append("RemoteOrder: %d" % r["remote_order"])
            if r["remote"]:
                fields.append("Remote: []Value{%s}" % ", ".join(r["remote"]))
        if r.get("two_state_kind"):
            fields.append("TwoState: %s" % r["two_state_kind"])
        if r.get("indie"):
            fields.append("IndieOrder: %d" % r["indie"])
        for flag, key in (("forces_int", "ForcesInt"), ("move_tail", "MoveTail")):
            if r[flag]:
                fields.append("%s: true" % key)
        if r["verified"]:
            fields.append("Verified: %s" % json.dumps("ida " + " ".join(r["verified"])))
        out.append("\t{%s}," % ", ".join(fields))
    out.append("}")
    with open(a.output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
